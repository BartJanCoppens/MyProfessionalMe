// Prints the SQL that seeds the learning catalogue, curriculum mappings and knowledge bundles from src/data.ts.
// Run: node --experimental-strip-types scripts/seed-content.ts > <migration>.sql
import { AUD_MAPS0, BUNDLES0, LEARN, MAPS0, PUB } from '../src/data.ts';

const q = (v: string | number | null) => (v === null ? 'null' : typeof v === 'number' ? String(v) : "'" + v.replace(/'/g, "''") + "'");
const status = (id: string) => (PUB[id] ? (PUB[id][1] === 'Draft' ? 'draft' : 'review') : 'published');
// Bundles belong to the business line of their owner; firm-wide teams own the rest.
const LINE: Record<string, string | null> = { B1: 'Consulting', B5: 'Consulting', B3: 'Consulting', B2: 'Tax & Legal', B7: null, B4: null, B8: null };

const out: string[] = ['-- Seed content from src/data.ts (generated by scripts/seed-content.ts).', ''];
out.push('insert into public.learnings (id, title, domain, level, format, source, hours, cpd, due, why, business_line, status) values');
out.push(LEARN.map((r) => '  (' + [r[0], r[1], r[2], r[3], r[4], r[5], r[6], r[7], r[8], r[9], null, status(r[0])].map(q).join(', ') + ')').join(',\n') + ';', '');
const maps = { ...MAPS0, ...AUD_MAPS0 };
out.push('insert into public.curriculum_mappings (audience, learning_id, stage, obligation) values');
out.push(Object.keys(maps).flatMap((aud) => maps[aud].map((m) => '  (' + [aud, m[0], m[1], m[2]].map(q).join(', ') + ')')).join(',\n') + ';', '');
out.push('insert into public.knowledge_bundles (id, business_line, access, data) values');
out.push(BUNDLES0.map((b) => '  (' + [b.id, b.id in LINE ? LINE[b.id] : null, b.access].map(q).join(', ') + ', ' + q(JSON.stringify(b)) + '::jsonb)').join(',\n') + ';');
console.log(out.join('\n'));
